static inline float isolation_forest_avg_path(int n) {
    if (n <= 1) return 0.0f;
    if (n == 2) return 1.0f;
    return 2.0f * (logf((float)(n - 1)) + 0.5772156649f)
         - 2.0f * (float)(n - 1) / (float)n;
}

static inline void isolation_forest_make_features(const float *r, float *o) {
    const float ax = r[3];
    const float ay = r[4];
    const float az = r[5];
    const float resultant = r[6];
    const float gx = r[7];
    const float gy = r[8];
    const float gz = r[9];
    const float gyroNorm = sqrtf(gx*gx + gy*gy + gz*gz);
    const float accDeviation = fabsf(resultant - 9.81f);

    o[0] = ax;
    o[1] = ay;
    o[2] = az - 9.81f;
    o[3] = resultant - 9.81f;
    o[4] = accDeviation;
    o[5] = gx;
    o[6] = gy;
    o[7] = gz;
    o[8] = gyroNorm;
    o[9] = r[13];

    for (int i = 0; i < 10; ++i) {
        const float s = (fabsf(iso_scale[i]) > 1e-12f) ? iso_scale[i] : 1.0f;
        o[i] = (o[i] - iso_center[i]) / s;
    }
}

